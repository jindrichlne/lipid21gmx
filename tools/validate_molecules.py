def all_specs():
    std = {tuple(v): k for k, v in L.standard_lipids().items()}
    specs = []
    tails = ['LAL', 'MY', 'PA', 'ST', 'OL', 'AR', 'DHA']
    for t1 in tails:
        for h in ['PC', 'PE', 'PS', 'PGR', 'PGS', 'PH-']:
            for t2 in tails:
                specs.append([t1, h, t2])
    for t in tails:
        specs.append([t, 'SPM', 'SA'])
    specs.append(['CHL'])
    return [(std.get(tuple(s), '_'.join(s).replace('-', 'm')), s) for s in specs]


def run(cmd, cwd, stdin=None):
    r = subprocess.run(cmd, cwd=cwd, input=stdin, capture_output=True, text=True, shell=isinstance(cmd, str))
    if r.returncode != 0:
        raise RuntimeError('%s failed:\n%s\n%s' % (cmd, r.stdout[-2000:], r.stderr[-2000:]))
    return r.stdout


def read_rst7(path, natom):
    lines = open(path).read().splitlines()
    vals = []
    for l in lines[2:]:
        vals += [float(l[i:i + 12]) for i in range(0, len(l), 12) if l[i:i + 12].strip()]
        if len(vals) >= 3 * natom:
            break
    return np.array(vals[:3 * natom]).reshape(natom, 3)


def read_mdcrd(path, natom):
    vals = []
    with open(path) as fh:
        fh.readline()
        for l in fh:
            vals += [float(l[i:i + 8]) for i in range(0, len(l.rstrip('\n')), 8)]
    vals = np.array(vals)
    nfr = len(vals) // (3 * natom)
    return vals[:nfr * 3 * natom].reshape(nfr, natom, 3)


# ---------------------------------------------------------------- gmx dump --
def parse_tpr_dump(text):
    ftypes = {}
    for m in re.finditer(r'functype\[(\d+)\]=(\w+), (.*)', text):
        vals = dict((k.strip(), float(v)) for k, v in re.findall(r'(\w+)=\s*([-+0-9.eE]+)', m.group(3)))
        ftypes[int(m.group(1))] = (m.group(2), vals)
    lists = {}
    for name in ('Bond', 'Angle', 'Proper Dih.', 'Per. Imp. Dih.', 'LJ-14'):
        m = re.search(r'\n {6}%s:\n {9}nr: (\d+)\n(?: {9}iatoms:\n)?((?: {12}\d+ type=.*\n)*)' % re.escape(name), text)
        items = []
        if m:
            for l in m.group(2).splitlines():
                f = l.split()
                t = int(f[1].split('=')[1])
                items.append((t, tuple(int(x) for x in f[3:])))
        lists[name] = items
    atoms = []
    for m in re.finditer(r'atom\[\s*\d+\]=\{type=\s*(\d+).*?m=\s*([-+0-9.eE]+), q=\s*([-+0-9.eE]+)', text):
        atoms.append((int(m.group(1)), float(m.group(2)), float(m.group(3))))
    fq = re.search(r'fudgeQQ\s*=\s*([0-9.eE+-]+)', text)
    return ftypes, lists, atoms, float(fq.group(1))


def compare_tpr(dump_text, prm, emulate=False, charge_adjust=None):
    """Compare GROMACS' processed interactions with the prmtop (Amber units converted)."""
    ftypes, lists, atoms, fudgeqq = parse_tpr_dump(dump_text)
    errs = []
    rel = lambda a, b: abs(a - b) / max(abs(a), abs(b), 1e-30)
    tol = 2e-5  # gmx dump prints 6 significant digits
    n = prm.natom
    if len(atoms) != n:
        return ['atom count %d vs %d' % (len(atoms), n)]
    qs = math.sqrt(K_AMBER / K_GMX) if emulate else 1.0
    for i, (t, m, q) in enumerate(atoms):
        qref = (prm.charges[i] + (charge_adjust or {}).get(i, 0.0)) * qs
        if abs(q - qref) > 6e-6 * max(1.0, abs(q)) or rel(m, prm.masses[i]) > tol:
            errs.append('atom %d q/m %g %g vs %g %g' % (i, q, m, prm.charges[i], prm.masses[i]))
    # bonds
    pb = {(min(i, j), max(i, j)): (k, r) for i, j, k, r in prm.bonds}
    gb = {}
    for t, (i, j) in lists['Bond']:
        ft, v = ftypes[t]
        gb[(min(i, j), max(i, j))] = (v['cbA'] / (2 * KCAL * 100), v['b0A'] * 10)
    if set(pb) != set(gb):
        errs.append('bond sets differ (%d vs %d)' % (len(gb), len(pb)))
    for k in set(pb) & set(gb):
        if rel(pb[k][0], gb[k][0]) > tol or rel(pb[k][1], gb[k][1]) > tol:
            errs.append('bond %s %s vs %s' % (k, gb[k], pb[k]))
    # angles
    fac = LEAP_DEG if emulate else 1.0
    pa = {(min(i, k), j, max(i, k)): (kk, th) for i, j, k, kk, th in prm.angles}
    ga = {}
    for t, (i, j, k) in lists['Angle']:
        ft, v = ftypes[t]
        ga[(min(i, k), j, max(i, k))] = (v['ctA'] / (2 * KCAL), v['thA'])
    if set(pa) != set(ga):
        errs.append('angle sets differ (%d vs %d)' % (len(ga), len(pa)))
    for k in set(pa) & set(ga):
        # prmtop theta0 carries LEaP's pi=3.141594; compare with the nominal value
        if rel(pa[k][0], ga[k][0]) > tol or rel(pa[k][1] / LEAP_DEG * fac, ga[k][1]) > 2e-6:
            errs.append('angle %s %s vs %s' % (k, ga[k], pa[k]))
    # proper torsions (grompp drops zero-amplitude terms, so drop them here too)
    def canon(q):
        return q if q[0] < q[3] else q[::-1]
    pp, pimp = {}, []
    for (i, j, k, l, pk, ph, pn, imp, ign, scee, scnb) in prm.dihedrals:
        if imp:
            pimp.append(((i, j, k, l), (pk, ph, pn)))
        elif pk != 0.0:
            pp.setdefault(canon((i, j, k, l)), []).append((round(pk * KCAL, 4), round(ph / LEAP_DEG * fac % 360, 2), int(pn)))
    gp = {}
    for t, q in lists['Proper Dih.']:
        ft, v = ftypes[t]
        gp.setdefault(canon(q), []).append((round(v['cpA'], 4), round(v['phiA'] % 360, 2), int(v['mult'])))
    if set(pp) != set(gp):
        errs.append('proper torsion quartets differ: %d vs %d' % (len(gp), len(pp)))
    for k in set(pp) & set(gp):
        a, b = sorted(pp[k]), sorted(gp[k])
        if len(a) != len(b) or any(abs(x[0] - y[0]) > 2e-4 * max(1, abs(x[0])) or abs(x[1] - y[1]) > 0.011 or x[2] != y[2]
                                   for x, y in zip(a, b)):
            errs.append('torsion %s gmx %s vs amber %s' % (k, b, a))
    # impropers: same atoms in the same order (or fully reversed = same angle)
    gi = {}
    for t, q in lists['Per. Imp. Dih.']:
        ft, v = ftypes[t]
        gi[canon(q)] = (round(v['cpA'] / KCAL, 5), round(v['phiA'] % 360, 2), int(v['mult']))
    pi_ = {canon(q): (round(pk, 5), round(ph / LEAP_DEG * fac % 360, 2), int(pn)) for q, (pk, ph, pn) in pimp}
    if gi != pi_:
        errs.append('impropers differ:\n   gmx   %s\n   amber %s' % (sorted(gi.items()), sorted(pi_.items())))
    # 1-4 pairs: c6/c12 vs Amber B/SCNB, A/SCNB; Coulomb via fudgeQQ = 1/SCEE
    p14 = prm.pairs14()
    g14 = {}
    for t, (i, j) in lists['LJ-14']:
        ft, v = ftypes[t]
        g14[(min(i, j), max(i, j))] = (v['c6A'], v['c12A'])
    if set(p14) != set(g14):
        errs.append('1-4 pair sets differ: %d vs %d' % (len(g14), len(p14)))
    for k in set(p14) & set(g14):
        A, B = prm.lj_ab(*k)
        scee, scnb = p14[k]
        c6, c12 = B / scnb * KCAL * 1e-6, A / scnb * KCAL * 1e-12
        if rel(c6, g14[k][0]) > tol or rel(c12, g14[k][1]) > tol:
            errs.append('LJ-14 %s c6/c12 %s vs %s (SCNB=%g)' % (k, g14[k], (c6, c12), scnb))
        if abs(fudgeqq - 1.0 / scee) > 1e-6:
            errs.append('fudgeQQ %g vs 1/SCEE %g' % (fudgeqq, 1 / scee))
    stats = {'bonds': len(gb), 'angles': len(ga), 'proper_terms': sum(len(v) for v in gp.values()),
             'impropers': len(gi), 'pairs14': len(g14),
             'pairs14_scnb6': sum(1 for k, v in p14.items() if v[1] != 2.0)}
    return errs, stats


def parse_forces(dump_text, natom):
    frames = []
    for m in re.finditer(r'\n\s+f \((\d+)x3\):\n((?:\s+f\[\s*\d+\]=\{.*\}\n)+)', dump_text):
        f = [[float(x) for x in re.search(r'\{(.*)\}', l).group(1).split(',')] for l in m.group(2).strip().splitlines()]
        frames.append(np.array(f))
    return frames


# -------------------------------------------------------------- one molecule --
def prepare_ffdir(wd, variant):
    """Copy of lipid21.ff for the variant (emulate: LEaP conventions in ffbonded.itp)."""
    dst = os.path.join(wd, 'lipid21.ff')
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(FFDIR, dst)
    if variant == 'emulate':
        out = []
        sec = None
        for l in open(os.path.join(dst, 'ffbonded.itp')):
            s = l.split(';')[0].split()
            if l.strip().startswith('['):
                sec = l.strip()
            elif s and sec == '[ angletypes ]':
                s[4] = repr(float(s[4]) * LEAP_DEG)
                l = '  ' + ' '.join(s) + '\n'
            elif s and sec == '[ dihedraltypes ]':
                s[5] = repr(float(s[5]) * LEAP_DEG)
                l = '  ' + ' '.join(s) + '\n'
            out.append(l)
        open(os.path.join(dst, 'ffbonded.itp'), 'w').write(''.join(out))
    return dst


def scale_charges_itp(src, dst, factor):
    out, sec = [], None
    for l in open(src):
        if l.strip().startswith('['):
            sec = l.strip()
        elif sec == '[ atoms ]' and l.split(';')[0].strip():
            f = l.split()
            f[6] = repr(float(f[6]) * factor)
            l = ' '.join(f) + '\n'
        out.append(l)
    open(dst, 'w').write(''.join(out))


VARIANTS = [  # label, force-field mode, rigid translation of all frames (nm)
    ('standalone', 'standalone', (0.0, 0.0, 0.0)),
    ('amber19sb', 'amber19sb', (0.0, 0.0, 0.0)),
    ('emulate', 'emulate', (0.0, 0.0, 0.0)),
    ('standalone_shifted', 'standalone', (0.37, 0.53, 0.71)),   # GROMACS float32 noise floor
]


def gmx_variant(wd, name, itp, frames_nm, atoms, label, variant, prm, shift, charge_adjust):
    vd = os.path.join(wd, label)
    os.makedirs(vd, exist_ok=True)
    frames_nm = [x + np.array(shift) for x in frames_nm]
    prepare_ffdir(vd, variant)
    molitp = os.path.join(vd, 'mol.itp')
    if variant == 'emulate':
        scale_charges_itp(itp, molitp, math.sqrt(K_AMBER / K_GMX))
    else:
        shutil.copy(itp, molitp)
    if variant == 'amber19sb':
        head = '#include "amber19sb.ff/forcefield.itp"\n#include "lipid21.ff/lipid21_params.itp"\n'
    else:
        head = '#include "lipid21.ff/forcefield.itp"\n'
    open(os.path.join(vd, 'topol.top'), 'w').write(
        head + '#include "mol.itp"\n\n[ system ]\n%s\n\n[ molecules ]\n%s 1\n' % (name, molname(itp)))
    open(os.path.join(vd, 'vac.mdp'), 'w').write(MDP)
    box = (15.0, 15.0, 15.0)
    gmxio.write_g96(os.path.join(vd, 'conf.g96'), atoms, frames_nm[:1], box)
    gmxio.write_g96(os.path.join(vd, 'frames.g96'), atoms, frames_nm, box)
    env = {'GMX_AMBER_LEAP_ATOM_REORDERING_VERBOSE': '1'}
    log = gmxio.gmx(['grompp', '-f', 'vac.mdp', '-c', 'conf.g96', '-p', 'topol.top', '-o', 'vac.tpr', '-maxwarn', '0'], vd, env=env)
    open(os.path.join(vd, 'grompp.log'), 'w').write(log)
    dump = gmxio.gmx(['dump', '-s', 'vac.tpr'], vd)
    tpr_errs, tpr_stats = compare_tpr(dump, prm, emulate=(variant == 'emulate'), charge_adjust=charge_adjust)
    gmxio.gmx(['mdrun', '-s', 'vac.tpr', '-rerun', 'frames.g96', '-deffnm', 'vac', '-nt', '1'], vd)
    gmxio.gmx(['energy', '-f', 'vac.edr', '-o', 'ener.xvg'], vd, stdin='\n'.join(t.replace(' ', '-') for t in TERMS) + '\n\n')
    leg, rows = gmxio.read_xvg(os.path.join(vd, 'ener.xvg'))
    e = {t: [r[1 + leg.index(t)] if t in leg else 0.0 for r in rows] for t in TERMS}
    fdump = gmxio.gmx(['dump', '-f', 'vac.trr'], vd)
    forces = parse_forces(fdump, len(atoms))
    reorder = [l for l in log.splitlines() if 'To match AMBER LEaP ordering' in l]
    return e, forces, tpr_errs, tpr_stats, reorder


def molname(itp):
    lines = open(itp).read().split('[ moleculetype ]')[1].splitlines()
    return [l for l in lines if l.strip() and not l.strip().startswith(';')][0].split()[0]


def validate(spec, outroot, ff, keep=False, seed=2022):
    name, residues = spec
    wd = os.path.join(outroot, 'work', name)
    os.makedirs(wd, exist_ok=True)
    res = {'name': name, 'residues': residues}
    try:
        build = 'm = copy CHL' if residues == ['CHL'] else 'm = sequence { %s }' % ' '.join(residues)
        open(os.path.join(wd, 'build.leap'), 'w').write(
            'source leaprc.lipid21\n%s\nsaveamberparm m mol.prmtop mol.inpcrd\nquit\n' % build)
        out = run(['tleap', '-f', 'build.leap'], wd)
        res['tleap_warnings'] = [l for l in out.splitlines() if 'No torsion' in l or 'Could not find' in l]
        open(os.path.join(wd, 'min.in'), 'w').write(MIN_IN)
        open(os.path.join(wd, 'md.in'), 'w').write(MD_IN % seed)
        run(['sander', '-O', '-i', 'min.in', '-p', 'mol.prmtop', '-c', 'mol.inpcrd', '-o', 'min.out', '-r', 'min.rst7'], wd)
        run(['sander', '-O', '-i', 'md.in', '-p', 'mol.prmtop', '-c', 'min.rst7', '-o', 'md.out', '-r', 'md.rst7',
             '-x', 'md.crd'], wd)
        prm = Prmtop(os.path.join(wd, 'mol.prmtop'))
        n = prm.natom
        frames = [read_rst7(os.path.join(wd, 'min.rst7'), n)] + list(read_mdcrd(os.path.join(wd, 'md.crd'), n))
        # Amber energies and forces (pysander, vacuum, no cut-off)
        import sander
        amb_e, amb_f = [], []
        with sander.setup(os.path.join(wd, 'mol.prmtop'), frames[0], None, sander.gas_input()):
            for x in frames:
                sander.set_positions(x)
                e, f = sander.energy_forces()
                amb_e.append({'bond': e.bond, 'angle': e.angle, 'dihedral': e.dihedral, 'vdw_14': e.vdw_14,
                              'elec_14': e.elec_14, 'vdw': e.vdw, 'elec': e.elec, 'tot': e.tot})
                amb_f.append(np.array(f).reshape(n, 3))
        # GROMACS
        mol = L.Molecule(ff, residues, name)
        res['charge_adjust'] = {prm.names[i]: d for i, d in mol.charge_adjust.items()}
        itp = os.path.join(FFDIR, name + '.itp')
        if not os.path.exists(itp):
            itp = os.path.join(wd, name + '.itp')
            open(itp, 'w').write(mol.itp(['generated for validation']))
        atoms = [(prm.resnum[i] + 1, prm.resname[i], prm.names[i]) for i in range(n)]
        frames_nm = []
        for x in frames:
            c = x / 10.0
            frames_nm.append(c - c.mean(0) + 7.5)
        res['nframes'] = len(frames)
        res['variants'] = {}
        gmx_runs = {}
        for label, variant, shift in VARIANTS:
            gmx_runs[label] = gmx_variant(wd, name, itp, frames_nm, atoms, label, variant, prm, shift, mol.charge_adjust)
        famb = [f * KCAL * 10.0 for f in amb_f]                 # kJ/mol/nm
        frms = float(np.sqrt(np.mean([(np.linalg.norm(f, axis=1) ** 2).mean() for f in famb])))
        for label, variant, shift in VARIANTS:
            e, forces, tpr_errs, tpr_stats, reorder = gmx_runs[label]
            if label == 'standalone_shifted':
                # compare with the unshifted GROMACS run: numerical noise floor of mixed precision
                e0, f0 = gmx_runs['standalone'][0], gmx_runs['standalone'][1]
                ref_e = {t: np.array(e0[t]) for t in TERMS}
                ref_e['Dihedral'] = np.array(e0['Proper Dih.']) + np.array(e0['Per. Imp. Dih.'])
                ref_f = f0
            else:
                kq = 1.0 if variant == 'emulate' else K_GMX / K_AMBER
                conv = {'Bond': ('bond', 1), 'Angle': ('angle', 1), 'Dihedral': ('dihedral', 1),
                        'LJ-14': ('vdw_14', 1), 'Coulomb-14': ('elec_14', kq), 'LJ (SR)': ('vdw', 1),
                        'Coulomb (SR)': ('elec', kq)}
                ref_e = {t: np.array([d[a] * KCAL * sc for d in amb_e]) for t, (a, sc) in conv.items()}
                ref_e['Potential'] = sum(ref_e[t] for t in conv)
                ref_f = famb
            cmp = {}
            for label2, gterms in [('Bond', ['Bond']), ('Angle', ['Angle']),
                                   ('Dihedral', ['Proper Dih.', 'Per. Imp. Dih.']), ('LJ-14', ['LJ-14']),
                                   ('Coulomb-14', ['Coulomb-14']), ('LJ (SR)', ['LJ (SR)']),
                                   ('Coulomb (SR)', ['Coulomb (SR)']), ('Potential', ['Potential'])]:
                g = np.array([sum(e[t][k] for t in gterms) for k in range(len(frames))])
                a = ref_e[label2]
                scale = float(np.sqrt(np.mean(a ** 2)))
                cmp[label2] = {'max_abs': float(np.max(np.abs(g - a))),
                               'rel_to_rms': float(np.max(np.abs(g - a)) / max(scale, 1e-12)),
                               'rms_value': scale}
            dF = [np.linalg.norm(fg - fr, axis=1) for fg, fr in zip(forces, ref_f)]
            res['variants'][label] = {
                'energy': cmp, 'tpr_errors': tpr_errs, 'tpr_stats': tpr_stats,
                'force_max_abs': float(max(d.max() for d in dF)),
                'force_rms_abs': float(np.sqrt(np.mean([(d ** 2).mean() for d in dF]))),
                'force_rms_value': frms, 'nforce_frames': len(forces), 'reorder_log': reorder}
        res['ok'] = True
    except Exception:
        res['ok'] = False
        res['error'] = traceback.format_exc()
    if not keep and res.get('ok'):
        shutil.rmtree(wd, ignore_errors=True)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-o', '--outdir', default=os.path.join(ROOT, 'validation', 'molecules'))
    ap.add_argument('-j', '--jobs', type=int, default=max(1, (os.cpu_count() or 2) - 2))
    ap.add_argument('--only', nargs='*', help='molecule names to run (default: all)')
    ap.add_argument('--keep', action='store_true', help='keep work directories')
    args = ap.parse_args()
    ff = L.ForceField(os.path.join(L.DEFAULT_SRC, 'lipid21.lib'), os.path.join(L.DEFAULT_SRC, 'lipid21.dat'))
    specs = all_specs()
    if args.only:
        specs = [s for s in specs if s[0] in args.only]
    os.makedirs(args.outdir, exist_ok=True)
    with mp.Pool(args.jobs) as pool:
        results = pool.starmap(validate, [(s, args.outdir, ff, args.keep) for s in specs])
    json.dump(results, open(os.path.join(args.outdir, 'results.json'), 'w'), indent=1)
    bad = [r['name'] for r in results if not r['ok']]
    print('%d molecules, %d failed to run: %s' % (len(results), len(bad), bad))
    for r in results:
        if not r['ok']:
            print(r['name'], r['error'][-1500:])


