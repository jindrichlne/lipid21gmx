#!/usr/bin/env python
"""Single-molecule validation of the GROMACS Lipid21 port against Amber.

For every requested molecule (default: all 7x6x7 glycerophospholipid residue
combinations, 7 sphingomyelins and cholesterol):

 1. tleap builds the Amber reference topology (prmtop),
 2. sander minimises it in vacuum and runs 20 ps of vacuum MD at 450 K
    (frames every 2 ps) to obtain strongly off-equilibrium conformations,
 3. Amber energies and forces of every frame are evaluated with pysander
    (vacuum, no cut-off),
 4. GROMACS topologies are written (the shipped lipid21.ff/<NAME>.itp when the
    molecule is a standard lipid, otherwise generated by lipid21_gmx.py),
    processed by grompp, and the interaction lists in the .tpr (gmx dump) are
    compared term by term with the prmtop,
 5. gmx mdrun -rerun evaluates the same frames in a 15 nm box with plain 6 nm
    cut-offs without potential modifiers (= no cut-off for these molecules),
 6. energy components and forces are compared.

Three GROMACS variants are evaluated:
  standalone : #include "lipid21.ff/forcefield.itp"
  amber19sb  : #include "amber19sb.ff/forcefield.itp" + "lipid21.ff/lipid21_params.itp"
               (activates GROMACS' _FF_AMBER_LEAP_ATOM_REORDERING)
  emulate    : standalone, but with LEaP's numerical conventions reproduced
               (degree->radian with pi=3.141594, Amber's Coulomb constant via
               scaled charges) -- isolates the only expected differences.

Run with the AmberTools Python (needs numpy and pysander):
    source $AMBERHOME/amber.sh
    $AMBERHOME/miniconda/bin/python tools/validate_molecules.py -o validation/molecules
"""
